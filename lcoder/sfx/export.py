"""Getting sounds out: WAV files, recipe JSON, and a standalone Python pack.

The pack is the interesting one. VertexUI's own sound module exists because
a frozen one-file exe that carries audio assets has something to lose track
of, so shipping a folder of .wav files back into that app would undo the
point. `export_pack` writes a single .py with the audio inlined and a
SoundSet-shaped class around it, which drops in as a replacement for
vertexui.sound.SoundSet and needs nothing at runtime but the stdlib.
"""

import base64
import io
import json
import re
import wave

import numpy as np

from . import engine as E
from .recipe import Recipe, render


def trim(audio, floor_db=-62.0, pad_ms=12.0):
    """Cut the inaudible end off a tail, saving most of a file's size.

    The implementation moved to the engine, where the renderer can reach it
    too; this name stays because it is what the exporter means by trimming.
    """
    return E.trim_tail(audio, floor_db, pad_ms)


def wav_bytes(audio, bits=16, mono=False):
    """float array (n,2) or (n,) -> WAV file bytes."""
    if bits not in (16, 24):
        raise ValueError("bits must be 16 or 24 - the stdlib wave module "
                         "only writes PCM, and a float32 payload under a "
                         "PCM header is a file that lies about itself")
    a = np.asarray(audio, dtype=np.float64)
    if a.ndim == 1:
        a = a[:, None]
    if mono and a.shape[1] > 1:
        a = a.mean(axis=1, keepdims=True)
    a = np.clip(a, -1.0, 1.0)

    if bits == 24:
        ints = np.round(a * 8388607.0).astype(np.int32)
        raw = ints.reshape(-1, 1).view(np.uint8).reshape(-1, 4)[:, :3].tobytes()
        width = 3
    else:
        raw = np.round(a * 32767.0).astype("<i2").tobytes()
        width = 2

    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        w.setnchannels(a.shape[1])
        w.setsampwidth(width)
        w.setframerate(E.RATE)
        w.writeframes(raw)
    return buf.getvalue()


def safe_name(name, fallback="sound"):
    s = re.sub(r"[^A-Za-z0-9_.-]+", "_", str(name)).strip("_.")
    return s or fallback


def write_wav(path, audio, bits=16, mono=False, tail=True):
    data = wav_bytes(trim(audio) if tail else audio, bits, mono)
    with open(path, "wb") as fh:
        fh.write(data)
    return len(data)


def write_json(path, recipes):
    """One recipe or a dict/list of them, as a re-importable document."""
    if isinstance(recipes, Recipe):
        doc = {"version": 1, "sounds": [recipes.to_dict()]}
    elif isinstance(recipes, dict):
        doc = {"version": 1, "sounds": [r.to_dict() for r in recipes.values()]}
    else:
        doc = {"version": 1, "sounds": [r.to_dict() for r in recipes]}
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(doc, fh, indent=2)
    return doc


def read_json(path):
    with open(path, encoding="utf-8") as fh:
        doc = json.load(fh)
    return [Recipe.from_dict(d) for d in doc.get("sounds", [])]


_PACK_HEAD = '''"""{title}

Generated by SFX Forge - every cue is inlined as WAV bytes, so this module
is the whole dependency: no asset folder, no loader, nothing for a frozen
one-file build to lose track of.

    from {module} import sfx
    sfx.play("click")

It is shaped like vertexui.sound.SoundSet, so it can be handed straight to
the toolkit and every widget will use these cues instead of the defaults:

    import vertexui as vui
    from {module} import sfx
    vui.sound.use(sfx)
"""

import array
import base64
import queue
import threading
import time

RATE = {rate}

# name -> base64 WAV
_DATA = {{
{data}}}


class SoundSet:
    """Plays the inlined cues. Never blocks the caller, never raises."""

    def __init__(self, volume=1.0, enabled=True, gap=0.045):
        self.volume = float(volume)
        self.enabled = bool(enabled)
        self.gap = float(gap)
        self.specs = {{k: None for k in _DATA}}   # for API compatibility
        self._cache = {{}}
        self._q = None
        self._last = 0.0
        self._fails = 0

    def names(self):
        return sorted(_DATA)

    def wav(self, name):
        """WAV bytes for one cue, at the current volume."""
        key = (name, round(self.volume, 3))
        if key not in self._cache:
            raw = base64.b64decode(_DATA[name])
            if abs(self.volume - 1.0) > 0.001:
                head, body = raw[:44], raw[44:]
                pcm = array.array("h")
                pcm.frombytes(body[:len(body) // 2 * 2])
                v = self.volume
                for i, s in enumerate(pcm):
                    x = int(s * v)
                    pcm[i] = -32768 if x < -32768 else (32767 if x > 32767 else x)
                raw = head + pcm.tobytes()
            self._cache[key] = raw
        return self._cache[key]

    def _worker(self):
        import winsound
        while True:
            name = self._q.get()
            if name is None:
                return
            try:
                # winsound refuses SND_MEMORY together with SND_ASYNC, so
                # playback is synchronous here on the worker - blocking this
                # thread for the length of a cue costs nothing, while doing
                # it on the UI thread stutters every frame that makes a sound.
                winsound.PlaySound(self.wav(name),
                                   winsound.SND_MEMORY | winsound.SND_NODEFAULT)
            except Exception as exc:
                self._fails += 1
                if self._fails == 1:
                    print("Interface sounds unavailable: %r" % (exc,))
                if self._fails >= 3:
                    self.enabled = False
                    return

    def play(self, name="click"):
        if not self.enabled or name not in _DATA:
            return
        now = time.time()
        if now - self._last < self.gap:
            return
        self._last = now
        if self._q is None:
            self._q = queue.Queue(maxsize=2)
            threading.Thread(target=self._worker, name="sfxpack",
                             daemon=True).start()
        try:
            self._q.put_nowait(name)
        except queue.Full:
            pass          # one already in flight; dropping beats lagging


sfx = SoundSet()


def play(name="click"):
    sfx.play(name)
'''


def export_pack(path, sounds, title="Interface sounds.", mono=True):
    """Write a single self-contained .py holding every cue.

    `sounds` is {name: Recipe} or {name: float array}. Always 16-bit: the
    volume control in the generated module rescales the PCM through
    array("h"), and a 24-bit payload would be silently mangled by it.
    """
    bits = 16
    module = safe_name(str(path).replace("\\", "/").rsplit("/", 1)[-1]
                       .rsplit(".", 1)[0], "uisounds")
    chunks = []
    total = 0
    for name, item in sounds.items():
        audio = render(item) if isinstance(item, Recipe) else item
        # Trimming a loop would cut the wrap point off and reintroduce the
        # seam the renderer just removed.
        looped = isinstance(item, Recipe) and item.loop
        data = wav_bytes(audio if looped else trim(audio), bits=bits, mono=mono)
        total += len(data)
        b64 = base64.b64encode(data).decode("ascii")
        lines = [b64[i:i + 76] for i in range(0, len(b64), 76)]
        body = "\n".join('        "%s"' % ln for ln in lines)
        chunks.append('    %r: (\n%s\n    ),\n' % (str(name), body))

    src = _PACK_HEAD.format(title=title, module=module, rate=E.RATE,
                            data="".join(chunks))
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(src)
    return {"audio_bytes": total, "source_bytes": len(src),
            "count": len(sounds)}
